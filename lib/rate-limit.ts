/**
 * Счётчик со скользящим окном.
 *
 * Одна честная функция вместо трёх разных копий: `/api/lead` считает запросы
 * по IP, вебхук — по процессу, `lib/ai-memory.ts` — вызовы модели. Логика
 * окна у всех одна, и ошибка в ней (например, окно, которое сбрасывается
 * целиком, а не съезжает) стоила бы одинаково дорого во всех трёх местах.
 *
 * Хранение — в памяти процесса, как и остальное состояние бота. Из этого
 * прямо следует граница применимости, и её лучше знать заранее, чем выяснять
 * на инциденте: перезапуск контейнера обнуляет счётчики, а при нескольких
 * инстансах приложения потолок у каждого свой, то есть фактический потолок
 * умножается на число реплик. Для одного standalone-контейнера, которым
 * проект и деплоится, этого достаточно; при масштабировании нужен общий
 * счётчик (Redis), и переписывать придётся только этот модуль.
 */

export type WindowLimiter = {
  /** Пытается занять одно место в окне. `false` — потолок выбран. */
  tryConsume(now?: number): boolean;
  /** Сколько мест занято прямо сейчас. */
  used(now?: number): number;
  /** Только для тестов и диагностики. */
  reset(): void;
};

export function createWindowLimiter(limit: number, windowMs: number): WindowLimiter {
  // Отметки времени попыток. Длина массива ограничена сверху самим лимитом:
  // всё, что старше окна, выбрасывается на каждой проверке.
  let stamps: number[] = [];

  const prune = (now: number) => {
    stamps = stamps.filter((ts) => now - ts < windowMs);
  };

  return {
    tryConsume(now = Date.now()) {
      prune(now);
      if (stamps.length >= limit) return false;
      stamps.push(now);
      return true;
    },
    used(now = Date.now()) {
      prune(now);
      return stamps.length;
    },
    reset() {
      stamps = [];
    },
  };
}
