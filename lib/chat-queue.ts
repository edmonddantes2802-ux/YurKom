/**
 * Очередь задач на chatId: гарантирует, что для одного чата вторая задача
 * стартует только после того, как полностью завершится первая.
 *
 * Без этого два быстрых сообщения одного клиента подряд читают историю
 * диалога параллельно — оба видят её ещё пустой, второй ответ не учитывает
 * первый обмен, и бот здоровается дважды вместо связного разговора (см.
 * разбор в WORKLOG, инцидент 13:36–13:38).
 *
 * In-memory, per-process — тот же принцип, что и у остального состояния бота
 * (lib/ai-memory.ts): перезапуск контейнера очередь обнуляет, при нескольких
 * инстансах приложения у каждого своя. Задачи РАЗНЫХ chatId друг друга не
 * ждут — очередь по ключу, а не общая на процесс.
 */

const queues = new Map<string, Promise<void>>();

/**
 * Ставит задачу в очередь по `chatId`: ждёт завершения предыдущей задачи
 * этого же чата (если есть — иначе выполняется сразу), затем выполняет свою.
 * Результат (включая возможную ошибку) возвращается вызывающему как обычно.
 */
export function enqueueForChat<T>(chatId: string, task: () => Promise<T>): Promise<T> {
  const previous = queues.get(chatId) ?? Promise.resolve();
  const current = previous.then(task);
  // Хвост очереди никогда не должен упасть — иначе следующая задача этого
  // чата зависла бы на цепочке .then навсегда. Настоящий результат (успех
  // или ошибка) уходит вызывающему через `current`, а не через хвост.
  queues.set(
    chatId,
    current.then(
      () => undefined,
      () => undefined,
    ),
  );
  return current;
}

/** Только для тестов и диагностики. */
export function resetChatQueue(): void {
  queues.clear();
}
