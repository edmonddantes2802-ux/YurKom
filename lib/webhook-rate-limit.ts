/**
 * Потолок запросов к вебхуку бота — на процесс, а не на клиента.
 *
 * Почему не по идентификатору, как в `/api/lead`. У вебхука нет ни одного
 * пригодного ключа: `chat.id` приходит в теле запроса, то есть задаётся тем,
 * кого мы и собираемся ограничивать (ровно так обходилась квота модели), а IP
 * у всех апдейтов один и тот же — узла Telegram. Единственный честный вариант —
 * общий потолок на весь роут: он не зависит ни от чего, что можно подставить.
 *
 * Цена решения названа прямо: при всплеске настоящих обращений лимит отсечёт и
 * их тоже. Поэтому потолок выставлен с большим запасом относительно реального
 * трафика (единицы сообщений в минуту), а отсечка отвечает Telegram кодом 429,
 * а не 200 — Telegram доставит такой апдейт повторно, и настоящее обращение
 * задержится, но не пропадёт.
 */

import { createWindowLimiter } from '@/lib/rate-limit';

export const WEBHOOK_WINDOW_MS = 60_000;

/**
 * 60 запросов в минуту. Живой бот-секретарь для одной юридической службы столько
 * не набирает и близко; поток, который упирается в этот потолок, — это уже не
 * клиенты.
 */
export const WEBHOOK_MAX_PER_WINDOW = 60;

const limiter = createWindowLimiter(WEBHOOK_MAX_PER_WINDOW, WEBHOOK_WINDOW_MS);

/** Занимает место в окне. `false` — запрос нужно отсечь. */
export function allowWebhookRequest(now = Date.now()): boolean {
  return limiter.tryConsume(now);
}

/** Только для тестов и диагностики. */
export function resetWebhookRateLimit(): void {
  limiter.reset();
}
