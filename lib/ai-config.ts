/**
 * Стоп-паттерны постфильтра.
 *
 * Ответ, попавший хотя бы под один, клиенту НЕ уходит — вместо него штатный
 * шаблон. Это защита от prompt injection и от собственных фантазий модели:
 * обещание исхода, названная цена или статья как руководство к действию
 * дороже, чем сухой шаблон.
 *
 * Границы слов заданы явными lookaround'ами: `\b` в JS работает по ASCII и на
 * кириллице не срабатывает.
 */
export type StopPattern = { id: string; test: RegExp };

export const STOP_PATTERNS: StopPattern[] = [
  // --- Обещания результата ---
  { id: 'promise:гарантиру', test: /гарантиру/iu },
  { id: 'promise:выиграем', test: /выигра(ем|ете|ю|ешь)/iu },
  // «вернём деньги» ловим, «вернёмся к этому» — нет.
  { id: 'promise:вернём', test: /верн[её]м(?![а-яё])/iu },
  { id: 'promise:100%', test: /100\s*(%|процент)/iu },
  { id: 'promise:точно не', test: /точно\s+не(?![а-яё])/iu },
  { id: 'promise:обещаю', test: /обеща(ю|ем)(?![а-яё])/iu },

  // --- Цены и условия работы ---
  // «руб.», «рубль», «рублей» — но не «рубрика».
  { id: 'price:руб', test: /(?<![а-яё])руб(л|\.|(?![а-яё]))/iu },
  { id: 'price:бесплатн', test: /бесплатн/iu },
  { id: 'price:стоимость', test: /стоимост|расцен|прайс|(?<![а-яё])тариф/iu },
  { id: 'price:цена', test: /(?<![а-яё])цен[аыуе](?![а-яё])/iu },
  // Голое «стоит» не берём: «не стоит переживать» и «стоит обсудить с юристом»
  // — нормальные фразы, а ложное срабатывание глушит живой ответ шаблоном.
  { id: 'price:сколько стоит', test: /(сколько|это|услуга|работа|консультация)\s+(это\s+)?стоит|стоит\s+(от\s+)?\d/iu },

  // --- Нормы и статьи как руководство к действию ---
  { id: 'law:ст.N', test: /(?<![а-яё])(ст|п|ч)\.\s*\d/iu },
  { id: 'law:статья N', test: /(?<![а-яё])стать(я|и|е|ю|ей)\s*№?\s*\d/iu },
  { id: 'law:кодекс', test: /(УК|ГК|НК|АПК|ГПК|КоАП|ТК)\s*РФ/u },
  { id: 'law:ФЗ', test: /(\d\s*-?\s*ФЗ|ФЗ\s*[-–—№]?\s*\d)/u },
];

/** Первый сработавший стоп-паттерн или null. */
export function findStopPattern(text: string): string | null {
  for (const pattern of STOP_PATTERNS) {
    if (pattern.test.test(text)) return pattern.id;
  }
  return null;
}

/**
 * Классификация заявки с формы для сводки в рабочий чат.
 *
 * Отдельный короткий промпт, НЕ диалоговый: это разовая классификация текста,
 * а не разговор с клиентом. `SYSTEM_PROMPT` бота-секретаря сюда не подходит —
 * там инструкции «задавай по одному вопросу», «возьми контакт» и протокол
 * сводки, рассчитанные на многоходовый чат.
 *
 * Постфильтр стоп-паттернов здесь не нужен: сводка уходит команде, не
 * клиенту — обещание исхода или названная цена в внутренней заметке юриста
 * не несёт того риска, что в публичном ответе.
 */

