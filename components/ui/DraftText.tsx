import { Fragment } from 'react';

/**
 * Текст с плейсхолдерами `{{ФАКТ: ...}}`.
 *
 * Незаполненный фрагмент подсвечивается и помечается для скринридера. Смысл
 * не косметический: заготовка политики персональных данных внешне неотличима
 * от готового документа, а прочитанный как действующее условие плейсхолдер —
 * это обещание, которого никто не давал.
 *
 * Компонент серверный по умолчанию, но состояния и эффектов не использует,
 * поэтому импортируется и из клиентских (`Qualifier`).
 */

/** Захватывающая группа в split() оставляет разделители в результате. */
const PLACEHOLDER = /(\{\{[^}]*\}\})/g;

export function hasPlaceholder(text: string): boolean {
  return /\{\{[^}]*\}\}/.test(text);
}

export default function DraftText({ text }: { text: string }) {
  const parts = text.split(PLACEHOLDER);

  return (
    <>
      {parts.map((part, i) =>
        hasPlaceholder(part) ? (
          <mark key={i} className="draft-mark">
            {/* Подсветки достаточно глазу, но не диктору — отсюда скрытая
                приписка. Сам текст рендерится один раз: дублировать его в
                sr-only нельзя, при копировании страницы он бы удвоился. */}
            <span className="sr-only">Не заполнено: </span>
            {part}
          </mark>
        ) : (
          <Fragment key={i}>{part}</Fragment>
        ),
      )}
    </>
  );
}
